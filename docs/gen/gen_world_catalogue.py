#!/usr/bin/env python3
"""Generates the world catalogue of docs/user-guide/worlds.md:

* docs/assets/images/worlds/<world>.jpg   a thumbnail per usable world: Jo at its spawn pose, from
                                          behind and above (headless render);
* docs/includes/generated/world_catalogue.md   a grid of cards: thumbnail, class and RTF from the
                                          last `check_worlds --robot`, GNSS datum, spawn poses.

The worlds are those whose robot check passed with RTF >= 0.5 (user_worlds/.cache/world_status.json,
written by `./jo check --robot`). Each world is started headless in the container
(docs/gen/thumb_probe.py, fed on stdin): about 45 s per world, and it needs the GPU. Run it from the
repository root, with the container up:

    python3 docs/gen/gen_world_catalogue.py [--domain 79] [--partition jo_sim_docs] [--no-shoot] [world ...]

--no-shoot rewrites the catalogue from the metadata and the thumbnails already in docs/assets.
"""
import argparse, json, os, pathlib, subprocess, sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
CONTAINER = 'jo_sim-jo-sim-1'
STATUS = ROOT / 'user_worlds' / '.cache' / 'world_status.json'
THUMBS = ROOT / 'docs' / 'assets' / 'images' / 'worlds'
OUT = ROOT / 'docs' / 'includes' / 'generated' / 'world_catalogue.md'
HEADER = '<!-- Generated by docs/gen/gen_world_catalogue.py: do not edit by hand. -->\n\n'
# Camera offset (back, up) [m] from the spawn pose, where the default (7, 4) shows only the ground
VIEWS = {w: (18, 11) for w in ('city_osm_roundabout', 'city_osm_roundabout_combined', 'neighborhood',
                               'outdoor', 'small_city')}


def usable_worlds():
    status = json.load(open(STATUS))
    out = {}
    for name, v in sorted(status.items()):
        robot = v.get('robot') or {}
        rtf = robot.get('rtf') or 0
        if robot and not robot.get('issues') and rtf >= 0.5:
            out[name] = {'rtf': rtf, 'class': 'good' if rtf >= 0.8 else 'usable, slower',
                         'checked': robot.get('checked')}
    return out


def probe(worlds, a):
    env = ['-e', f'ROS_DOMAIN_ID={a.domain}', '-e', f'GZ_PARTITION={a.partition}']
    if a.no_shoot:
        env += ['-e', 'THUMB_META_ONLY=1']
    cmd = ('source /opt/ros/jazzy/setup.bash; source /home/ros/install/setup.bash; '
           'rm -rf /tmp/jo_sim/thumbs; python3 - "$@"; rc=$?; ros2 daemon stop >/dev/null 2>&1; exit $rc')
    with open(ROOT / 'docs' / 'gen' / 'thumb_probe.py') as f:
        text = subprocess.run(['docker', 'exec', '-i', *env, CONTAINER, 'bash', '-c', cmd, 'probe', *worlds],
                              stdin=f, stdout=subprocess.PIPE, check=True, text=True).stdout
    results = [json.loads(l) for l in text.splitlines() if l.strip()]
    if not a.no_shoot:
        THUMBS.mkdir(parents=True, exist_ok=True)
        for r in results:
            if 'thumb' in r:
                subprocess.run(['docker', 'cp', f"{CONTAINER}:{r['thumb']}", str(THUMBS / f"{r['world']}.jpg")],
                               check=True, capture_output=True)
    return results


def card(r, st):
    kind, lat, lon = r['datum']
    datum = {'world': f'the world\'s own ({lat:.4f}, {lon:.4f})', 'sidecar': f'sidecar ({lat:.4f}, {lon:.4f})',
             'default': 'default (Pisa)'}[kind]
    x, y, _, yaw = r['spawn']
    spawn = f'({x:g}, {y:g}), yaw {yaw:g}' + (f"; named: {', '.join(r['spawns'])}" if r['spawns'] else '')
    img = (f"![{r['world']}](../assets/images/worlds/{r['world']}.jpg){{ loading=lazy }}"
           if (THUMBS / f"{r['world']}.jpg").exists() else '*(no thumbnail)*')
    lines = [f"-   {img}", '', f"    **`{r['world']}`** · {st['class']} · RTF {st['rtf']:.2f}", '']
    if r['description']:
        lines += [f"    {r['description']}", '']
    lines += [f'    GNSS datum: {datum}<br>Spawn: {spawn}', '']
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--domain', type=int, default=79)
    ap.add_argument('--partition', default='jo_sim_docs')
    ap.add_argument('--no-shoot', action='store_true')
    ap.add_argument('worlds', nargs='*', help='only re-shoot these (the catalogue lists all usable worlds)')
    a = ap.parse_args()
    usable = usable_worlds()
    shoot = a.worlds or list(usable)
    if not a.no_shoot:
        probe([f'{w}@{VIEWS[w][0]},{VIEWS[w][1]}' if w in VIEWS else w for w in shoot], a)
    meta = probe(list(usable), argparse.Namespace(**{**vars(a), 'no_shoot': True}))
    failed = [r['world'] for r in meta if not (THUMBS / f"{r['world']}.jpg").exists()]
    body = [HEADER, f'{len(usable)} worlds: the ones whose last `./jo check --robot` passed with RTF ≥ 0.5. '
            'Jo is at the default spawn pose.\n', '<div class="grid cards" markdown>', '']
    body += [card(r, usable[r['world']]) for r in meta]
    body.append('</div>')
    OUT.write_text('\n'.join(body) + '\n')
    print(f'written: {OUT.relative_to(ROOT)} ({len(meta)} worlds); thumbnails missing: {failed or "none"}')


if __name__ == '__main__':
    sys.exit(main())
