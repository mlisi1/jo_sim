#!/usr/bin/env python3
"""Generates the measured tables of the docs (docs/includes/generated/):

* topics.md     every topic of the simulator: type, frame, rate (sim time), publisher QoS, nodes;
* tf_tree.md    the TF tree, as a mermaid diagram;
* nodes.md      every node: what it publishes and subscribes, and its parameters.

It starts a headless simulator in the container (docs/gen/topic_probe.py, fed on stdin) and
measures it: about two minutes, and it needs the GPU. Run it on a free machine, from the repository
root, with the container up:

    python3 docs/gen/gen_topics.py [--domain 79] [--partition jo_sim_docs] [launch args ...]

Run it again (and commit the result) when a topic, a frame, a rate or a node parameter changes.
"""
import argparse, json, pathlib, subprocess, sys
from container import container

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / 'docs' / 'includes' / 'generated'
HEADER = '<!-- Generated by docs/gen/gen_topics.py: do not edit by hand. -->\n\n'
TRANSPORTS = ('compressed', 'compressedDepth', 'theora', 'zstd', 'ffmpeg')
TRACK = ('roller', 'belt', 'cover')  # track geometry frames, left out of the diagram
# image_transport plugin parameters (declared on every image publisher): left out of nodes.md
IT_PARAMS = {'format', 'jpeg_quality', 'png_level', 'res_unit', 'xdpi', 'ydpi', 'depth_max',
             'depth_quantization', 'enable_pub_plugins', 'keyframe_frequency', 'optimize_for',
             'quality', 'target_bitrate', 'zstd_level'}
HIDDEN_PARAMS = ('start_type_description_service', 'use_sim_time', 'robot_description', 'qos_overrides')


def run_probe(domain, partition, launch_args):
    cmd = ('source /opt/ros/jazzy/setup.bash; source /home/ros/install/setup.bash; '
           'python3 - "$@"; rc=$?; ros2 daemon stop >/dev/null 2>&1; exit $rc')
    with open(ROOT / 'docs' / 'gen' / 'topic_probe.py') as f:
        r = subprocess.run(['docker', 'exec', '-i', '-e', f'ROS_DOMAIN_ID={domain}',
                            '-e', f'GZ_PARTITION={partition}', container(), 'bash', '-c', cmd, 'probe',
                            *launch_args], stdin=f, stdout=subprocess.PIPE, check=True, text=True)
    return json.loads(r.stdout)


def short(t):
    return t.replace('/msg/', '/')


def topics_md(d):
    topics = d['topics']
    transports = {}
    for name in topics:
        base, _, last = name.rpartition('/')
        if last in TRANSPORTS and base in topics:
            transports.setdefault(base, []).append(last)

    def qos(t):
        return '<br>'.join(f'{r}, {du}, {dep}' for r, du, dep in t['qos']) or '—'

    def rate(t):
        if t.get('hz') is None:
            return 'latched' if any(q[1] == 'transient_local' for q in t['qos']) else '—'
        return f"{t['hz']:g}" if t['hz'] else '0 (no publisher active)'

    def nodes(lst):
        return ', '.join(f'`{n}`' for n in lst) or '—'

    def table(names):
        rows = ['| Topic | Type | Frame | Rate [Hz] | QoS (reliability, durability, depth) | Published by | Subscribed by |',
                '|---|---|---|---|---|---|---|']
        for n in names:
            t = topics[n]
            topic = f'`{n}`'
            if n in transports:
                topic += '<br>+ ' + ', '.join(f'`{x}`' for x in sorted(transports[n]))
            rows.append(f"| {topic} | `{short(t['type'])}` | {('`' + t['frame'] + '`') if t.get('frame') else '—'} "
                        f"| {rate(t)} | {qos(t)} | {nodes(t['publishers'])} | {nodes(t['subscribers'])} |")
        return '\n'.join(rows) + '\n'

    hidden = {f'{b}/{x}' for b, xs in transports.items() for x in xs}
    robot = sorted(n for n in topics if not n.startswith('/sim/') and n not in hidden)
    sim = sorted(n for n in topics if n.startswith('/sim/'))
    return (HEADER + f"Measured on `{' '.join(d['launch'][3:])}`, rates in sim time.\n\n"
            '#### Robot interface\n\n' + table(robot) + '\n#### Simulation only\n\n' + table(sim))


def tf_md(d):
    edges = d['tf']
    track = sorted(c for c in edges if any(k in c for k in TRACK))
    lines = ['```mermaid', 'graph LR']
    ids = {}

    def nid(frame):
        return ids.setdefault(frame, f'f{len(ids)}')

    for child, (parent, static) in sorted(edges.items(), key=lambda e: (e[1][0], e[0])):
        if child in track:
            continue
        lines.append(f'  {nid(parent)}["{parent}"] {"-.->" if not static else "-->"} {nid(child)}["{child}"]')
    lines.append('```')
    note = (f'\nAll {len(edges)} transforms are static (`/tf_static`). The track geometry ('
            f'{len(track)} frames: rollers, belts and covers) is left out: ' + ', '.join(f'`{c}`' for c in track) + '.\n')
    return HEADER + '\n'.join(lines) + '\n' + note


def flatten(d, prefix=''):
    for k, v in d.items():
        if isinstance(v, dict):
            yield from flatten(v, f'{prefix}{k}.')
        else:
            yield f'{prefix}{k}', v


def nodes_md(d):
    topics = d['topics']

    def listed(names):
        # every node subscribes /clock (use_sim_time); image_transport sub-topics are listed on Topics
        names = [t for t in names if t != '/clock' and t.rpartition('/')[2] not in TRANSPORTS]
        return ', '.join(f'`{t}`' for t in sorted(names)) or '—'

    out = [HEADER + 'Every node runs with `use_sim_time: true` and subscribes `/clock`. The image_transport '
           'plugin parameters (`compressed`, `theora`, ...) are left out.\n']
    for node, params in sorted(d['params'].items()):
        pubs = [t for t, v in topics.items() if node in v['publishers']]
        subs = [t for t, v in topics.items() if node in v['subscribers']]
        out.append(f'#### `{node}`\n')
        out.append('- **Publishes:** ' + listed(pubs))
        out.append('- **Subscribes:** ' + listed(subs) + '\n')
        shown = [(k, v) for k, v in sorted(flatten(params))
                 if not k.startswith(HIDDEN_PARAMS) and k.rsplit('.', 1)[-1] not in IT_PARAMS
                 and not set(k.split('.')) & set(TRANSPORTS + ('tiff',))]
        if shown:
            out.append('| Parameter | Value |\n|---|---|')
            for k, v in shown:
                if isinstance(v, str) and v.startswith(('/home/', '/opt/')):
                    v = '…/' + v.rsplit('/', 1)[-1]  # install paths: keep the file name
                out.append(f'| `{k}` | `{json.dumps(v, ensure_ascii=False)}` |')
            out.append('')
    return '\n'.join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--domain', type=int, default=79)
    ap.add_argument('--partition', default='jo_sim_docs')
    ap.add_argument('--json', help='render from a saved probe output instead of running the sim')
    ap.add_argument('--save-json', help='also save the probe output here')
    ap.add_argument('launch_args', nargs='*')
    a = ap.parse_args()
    d = json.load(open(a.json)) if a.json else run_probe(a.domain, a.partition, a.launch_args)
    if a.save_json:
        json.dump(d, open(a.save_json, 'w'), indent=1)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / 'topics.md').write_text(topics_md(d))
    (OUT / 'tf_tree.md').write_text(tf_md(d))
    (OUT / 'nodes.md').write_text(nodes_md(d))
    print(f"written: topics.md ({len(d['topics'])} topics), tf_tree.md ({len(d['tf'])} frames), "
          f"nodes.md ({len(d['params'])} nodes)")


if __name__ == '__main__':
    sys.exit(main())
