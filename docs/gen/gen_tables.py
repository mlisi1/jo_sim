#!/usr/bin/env python3
"""Generates the reference tables included by the docs (docs/includes/generated/*.md):

* launch arguments of sim_bringup.launch.py / launch_sim.launch.py (from `ros2 launch --show-args`,
  run in the jo_sim container), grouped by where they come from;
* bridged topics, from jo_sim/config/bridge/*.yaml;
* the `./jo help` text.

Run from the repository root, with the container up:  python3 docs/gen/gen_tables.py
Run it again (and commit the result) whenever a launch argument, a bridge or ./jo changes.
"""
import pathlib, re, subprocess, sys
import yaml

ROOT = pathlib.Path(__file__).resolve().parents[2]
OUT = ROOT / 'docs' / 'includes' / 'generated'
CONTAINER = 'jo_sim-jo-sim-1'
HEADER = '<!-- Generated by docs/gen/gen_tables.py: do not edit by hand. -->\n\n'


def show_args(launch_file):
    cmd = ('source /opt/ros/jazzy/setup.bash; source /home/ros/install/setup.bash; '
           f'ros2 launch jo_sim {launch_file} --show-args')
    text = subprocess.run(['docker', 'exec', CONTAINER, 'bash', '-c', cmd],
                          check=True, capture_output=True, text=True).stdout
    args, cur = {}, None
    for line in text.splitlines():
        m = re.match(r"^    '([^']+)':$", line)
        if m:
            cur = m.group(1); args[cur] = {'desc': [], 'default': None}; continue
        if cur is None or not line.strip():
            continue
        d = re.match(r"^\s+\(default: (.*)\)$", line)
        if d:
            args[cur]['default'] = d.group(1).strip("'")
        else:
            args[cur]['desc'].append(line.strip())
    return args


def md_escape(s):
    return s.replace('|', '\\|').replace('<', '&lt;').replace('>', '&gt;')


def args_table(args, names):
    rows = ['| Argument | Default | Description |', '|---|---|---|']
    for n in names:
        a = args[n]
        desc = ' '.join(a['desc'])
        if desc == 'no description given':
            desc = ''
        default = a['default']
        default = '*(empty)*' if default == '' else f'`{default}`'
        if len(default) > 60:  # long paths: keep the last component
            default = f"`…/{a['default'].rstrip('/').split('/')[-1]}`"
        rows.append(f'| `{n}` | {default} | {md_escape(desc)} |')
    return '\n'.join(rows) + '\n'


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    bringup = show_args('sim_bringup.launch.py')
    sim = show_args('launch_sim.launch.py')
    # sim_bringup's own flags (same names and defaults as jo_bringup), declared with flag('name', ...)
    src = (ROOT / 'jo_sim' / 'launch' / 'sim_bringup.launch.py').read_text()
    robot_flags = [n for n in re.findall(r"flag\('([^']+)'", src) if n in bringup]
    # set by launch_sim when it includes jo_description's launch, not user arguments
    internal = {'use_rviz', 'use_ros2_control'}
    simulator = [n for n in sim if n not in robot_flags and n not in internal]
    stack = [n for n in bringup if n not in robot_flags and n not in sim and n not in internal]
    (OUT / 'launch_args_robot.md').write_text(HEADER + args_table(bringup, robot_flags))
    (OUT / 'launch_args_sim.md').write_text(HEADER + args_table(sim, simulator))
    (OUT / 'launch_args_stack.md').write_text(HEADER + args_table(bringup, stack))

    rows = ['| Bridge file | ROS topic | Gazebo topic | ROS type | Direction |', '|---|---|---|---|---|']
    for f in sorted((ROOT / 'jo_sim' / 'config' / 'bridge').glob('*.yaml')):
        for b in yaml.safe_load(f.read_text()) or []:
            ros = b['ros_topic_name']; ros = ros if ros.startswith('/') else '/' + ros
            arrow = {'GZ_TO_ROS': 'Gazebo → ROS', 'ROS_TO_GZ': 'ROS → Gazebo'}.get(b.get('direction'), 'both')
            rows.append(f"| `{f.name}` | `{ros}` | `{b['gz_topic_name']}` | `{b['ros_type_name']}` | {arrow} |")
    (OUT / 'bridges.md').write_text(HEADER + '\n'.join(rows) + '\n')

    help_text = subprocess.run([str(ROOT / 'jo'), 'help'], capture_output=True, text=True).stdout
    (OUT / 'jo_help.md').write_text(HEADER + '```text\n' + help_text.rstrip() + '\n```\n')
    print('written:', ', '.join(sorted(p.name for p in OUT.glob('*.md'))))
    print(f'arguments: robot flags {len(robot_flags)}, simulator {len(simulator)}, stack {len(stack)}')


if __name__ == '__main__':
    sys.exit(main())
